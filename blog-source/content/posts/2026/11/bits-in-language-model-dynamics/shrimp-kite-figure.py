"""Render the prior Qwen kite from compact local plotting inputs.

Place this file beside qwen-kite-plot-data.npz and qwen-kite-source.json.
Run: uv run --with numpy --with matplotlib python shrimp-kite-figure.py
Verify existing outputs: add --verify. No model or raw state arrays are needed.
Verification regenerates all nine images and their receipt in a temporary directory.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.transforms import Bbox
import numpy as np


def binding(path):
    return {"file": path.name, "size_bytes": path.stat().st_size,
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--input-dir", type=Path, default=Path(__file__).resolve().parent)
    ap.add_argument("--out-dir", type=Path)
    ap.add_argument("--verify", action="store_true")
    args = ap.parse_args()
    root = args.input_dir
    outdir = args.out_dir or root
    receipt_path = outdir / "qwen-kite-branches.receipt.json"
    if args.verify:
        receipt = json.loads(receipt_path.read_text())
        for item in receipt["inputs"]:
            assert binding(root / item["file"]) == item, item["file"]
        for item in receipt["outputs"]:
            assert binding(outdir / item["file"]) == item, item["file"]
        assert binding(Path(__file__)) == receipt["generator"]
        with tempfile.TemporaryDirectory(prefix="qwen-kite-verify-") as directory:
            regenerated = Path(directory)
            subprocess.run([sys.executable, str(Path(__file__).resolve()),
                            "--input-dir", str(root.resolve()), "--out-dir", str(regenerated)],
                           check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
            for name in [item["file"] for item in receipt["outputs"]] + [receipt_path.name]:
                assert (regenerated / name).read_bytes() == (outdir / name).read_bytes(), "Regenerated bytes differ: " + name
        print("Regenerated and verified all nine images and their receipt byte-for-byte; compact input and generator bindings also passed.")
        return
    metadata_path = root / "qwen-kite-source.json"
    metadata = json.loads(metadata_path.read_text())
    data_path = root / "qwen-kite-plot-data.npz"
    assert binding(data_path) == metadata["plot_data"], "Compact input binding differs"
    d = np.load(data_path, allow_pickle=False)
    summary = metadata["original_figure_summary"]
    bt = summary["branch_log10_temperature"]
    lo, hi = summary["coexistence_alpha"]
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 13,
                        "svg.fonttype": "none", "svg.hashsalt": "qwen-kite-portrait-v1"})
    fig, (axA, axB) = plt.subplots(2, 1, figsize=(6.8, 10.5),
                                  gridspec_kw={"height_ratios": [1.15, 1.0]})
    extent = d["map_extent"]
    axA.imshow(d["map_rgba"], origin="lower", aspect="auto", interpolation="nearest", extent=extent)
    for key, ls, color in (("flip_ad", "--", "r"), ("flip_td", "--", "r"), ("fold", "-", "k")):
        xy = d[key]
        axA.plot(xy[:, 0], xy[:, 1], ls, color=color, lw=1.4, zorder=4)
    axA.axhline(bt, color="tab:green", lw=.7, ls=":", zorder=3)
    axA.plot([lo, hi], [bt, bt], color="tab:green", lw=4, solid_capstyle="butt", zorder=5)
    located = summary["located"]
    for x, y, _ in located:
        axA.plot(x, y, "*", color="gold", ms=14, mec="k", mew=.6, zorder=7)
    labels = [(k, summary[k]) for k in ("R", "A", "B")]
    labels.append(("C", [located[0][:2]]))
    for name, values in labels:
        for p in values[:1]:
            if name != "C":
                axA.plot(*p, "o", ms=4, color="w", mec="k", mew=.6, zorder=8)
            axA.annotate(name, p, xytext=(5, 3), textcoords="offset points", fontsize=14,
                         weight="bold", color="k", zorder=9,
                         bbox=dict(boxstyle="round,pad=0.1", fc="w", ec="none", alpha=.75))
    axA.set_xlim(extent[:2]); axA.set_ylim(extent[2:])
    axA.set_xlabel(r"steering strength $\alpha$")
    axA.set_ylabel(r"$\log_{10}T$")
    axA.ticklabel_format(useOffset=False)
    axA.tick_params(labelsize=11)
    axA.xaxis.set_major_locator(plt.MaxNLocator(5))
    axA.set_title("(a) The period-6 kite", loc="left", fontsize=16, pad=12)

    lam, xproj, stable = d["branch_alpha"], d["branch_pc1"], d["branch_attracting"]
    good = stable[:-1] & stable[1:]
    k = 0
    while k < len(lam) - 1:
        j = k
        while j < len(lam) - 1 and good[j] == good[k]:
            j += 1
        axB.plot(lam[k:j+1], xproj[k:j+1], "-" if good[k] else "--",
                 color="tab:blue" if good[k] else "0.45", lw=2.0 if good[k] else 1.3)
        k = j
    for i in d["branch_turn_indices"]:
        axB.plot(lam[i], xproj[i], "o", ms=6, mfc="w", mec="k", zorder=5)
    axB.axvspan(lo, hi, color="tab:green", alpha=.15, lw=0)
    axB.set_xlabel(r"steering strength $\alpha$")
    axB.set_ylabel("orbit state: first principal coordinate")
    axB.ticklabel_format(useOffset=False)
    axB.tick_params(labelsize=11)
    axB.set_title("(b) Two attracting cycles at the same controls\n" +
                  r"$\log_{10}T=%.7f$; open circles mark folds" % bt,
                  fontsize=12.5, loc="left", pad=12)
    axB.plot([], [], "-", color="tab:blue", lw=2, label="attracting")
    axB.plot([], [], "--", color="0.45", lw=1.3, label="not attracting")
    axB.fill_between([], [], color="tab:green", alpha=.15, label="two attracting orbits")
    axB.legend(fontsize=10.5, loc="best")
    fig.tight_layout(h_pad=2.0)
    outdir.mkdir(parents=True, exist_ok=True)
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    crops = {}
    for name, ax in (("qwen-kite-map", axA), ("qwen-kite-branch", axB)):
        box = ax.get_tightbbox(renderer).transformed(fig.dpi_scale_trans.inverted())
        crops[name] = Bbox.from_extents(box.x0-.08, box.y0-.08, box.x1+.08, box.y1+.08)
    outputs = []
    for stem, box in [("qwen-kite-branches", "tight"), *crops.items()]:
        axA.set_visible(stem != "qwen-kite-branch")
        axB.set_visible(stem != "qwen-kite-map")
        for ext in ("png", "svg", "pdf"):
            path = outdir / f"{stem}.{ext}"
            save_metadata = {"Date": None} if ext == "svg" else ({"CreationDate": None, "ModDate": None} if ext == "pdf" else None)
            fig.savefig(path, dpi=240, bbox_inches=box, pad_inches=.08, metadata=save_metadata)
            if ext == "svg":
                path.write_bytes(b"\n".join(line.rstrip() for line in path.read_bytes().splitlines()) + b"\n")
            outputs.append(binding(path))
    plt.close(fig)
    receipt = {
        "description": "Portrait layout adaptation of the earlier period-6 kite figure, with the original displayed numerical data.",
        "scope": "This generator plots compact saved inputs only. No model evaluation, trajectories, continuation, PCA recomputation or new stability calculation.",
        "semantics": "Top: fixed-start map and fold/flip curves. Bottom: numerical orbit continuation, not a measured upward/downward hysteresis scan. The vertical coordinate is a principal-component display projection.",
        "inputs": [binding(data_path), binding(metadata_path)],
        "generator": binding(Path(__file__)),
        "outputs": outputs,
        "runtime": {"numpy": np.__version__, "matplotlib": matplotlib.__version__, "font": "DejaVu Sans"},
        "nominal_size_inches": [6.8, 10.5],
        "separate_exports": {name: {"scope": "Per-axis tight bounding box, including title, ticks, axis labels and legend where present; no plotted data removed.",
                                     "size_inches": [box.width, box.height]}
                             for name, box in crops.items()},
        "verification": "--verify regenerates nine images and this receipt in a temporary directory and compares all ten files byte-for-byte.",
    }
    receipt_path.write_text(json.dumps(receipt, indent=2) + "\n")
    print(json.dumps({"outputs": outputs, "receipt": receipt_path.name}))


if __name__ == "__main__":
    main()
